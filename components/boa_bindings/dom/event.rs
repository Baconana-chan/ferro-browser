/// CustomEvent initialization options
#[derive(Debug, Clone, Default)]
pub struct CustomEventInit {
    pub bubbles: bool,
    pub cancelable: bool,
    pub composed: bool,
    pub detail: Option<JsValue>,
}

/// CustomEvent - event with custom data
pub struct CustomEvent {
    /// Base event
    event: Event,
    
    /// Custom detail data
    detail: RefCell<JsValue>,
}

impl CustomEvent {
    /// Create a new CustomEvent
    pub fn new(event_type: &str) -> Self {
        CustomEvent {
            event: Event::new(event_type),
            detail: RefCell::new(JsValue::null()),
        }
    }

    /// Create a new CustomEvent with options
    pub fn new_with_options(event_type: &str, init: CustomEventInit) -> Self {
        let event_init = EventInit {
            bubbles: init.bubbles,
            cancelable: init.cancelable,
            composed: init.composed,
        };
        
        CustomEvent {
            event: Event::new_with_options(event_type, event_init),
            detail: RefCell::new(init.detail.unwrap_or(JsValue::null())),
        }
    }

    /// Get the base event
    pub fn event(&self) -> &Event {
        &self.event
    }

    /// Get the detail
    pub fn detail(&self) -> JsValue {
        self.detail.borrow().clone()
    }

    /// Set the detail
    pub fn set_detail(&self, detail: JsValue) {
        *self.detail.borrow_mut() = detail;
    }

    /// Initialize custom event (legacy method)
    pub fn init_custom_event(
        &mut self,
        type_: &str,
        bubbles: bool,
        cancelable: bool,
        detail: JsValue,
    ) {
        self.event.init_event(type_, bubbles, cancelable);
        if !self.event.is_dispatched() {
            *self.detail.borrow_mut() = detail;
        }
    }
}

impl ToJsValueBoa for CustomEvent {
    fn to_js_value(&self, ctx: &mut Context) -> JsResult<JsValue> {
        // Get base event as object
        let base = self.event.to_js_value(ctx)?;
        let obj = base.as_object()
            .map(|o| o.clone())
            .unwrap_or_else(JsObject::with_null_proto);
        
        // Add detail property
        obj.set(js_string!("detail"), self.detail(), false, ctx)?;
        
        Ok(JsValue::from(obj))
    }
}

