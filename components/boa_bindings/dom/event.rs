//! Event and CustomEvent Implementation for Boa
//!
//! Full Event implementation with bubbling, capturing, and propagation control.

use std::cell::RefCell;

use boa_engine::{
    Context, JsObject, JsResult, JsValue, js_string,
};

use crate::codegen::types::ToJsValueBoa;

/// Event phases
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EventPhase {
    None = 0,
    Capturing = 1,
    AtTarget = 2,
    Bubbling = 3,
}

impl Default for EventPhase {
    fn default() -> Self {
        EventPhase::None
    }
}

/// Event initialization options
#[derive(Debug, Clone, Default)]
pub struct EventInit {
    pub bubbles: bool,
    pub cancelable: bool,
    pub composed: bool,
}

/// Full Event implementation per DOM spec
#[derive(Clone)]
pub struct Event {
    /// Event type (e.g., "click", "keydown")
    event_type: String,
    
    /// Target of the event
    target: RefCell<Option<JsObject>>,
    
    /// Current target during dispatch
    current_target: RefCell<Option<JsObject>>,
    
    /// Related target (for mouse events, focus events, etc.)
    related_target: RefCell<Option<JsObject>>,
    
    /// Event phase
    event_phase: RefCell<EventPhase>,
    
    /// Whether event bubbles
    bubbles: bool,
    
    /// Whether event is cancelable
    cancelable: bool,
    
    /// Whether event is composed (crosses shadow DOM boundaries)
    composed: bool,
    
    /// Whether default was prevented
    default_prevented: RefCell<bool>,
    
    /// Whether propagation was stopped
    stop_propagation_flag: RefCell<bool>,
    
    /// Whether immediate propagation was stopped
    stop_immediate_propagation_flag: RefCell<bool>,
    
    /// Whether event was dispatched
    dispatched: RefCell<bool>,
    
    /// Whether event was initialized
    _initialized: bool,
    
    /// Whether event is trusted (generated by user agent)
    is_trusted: bool,
    
    /// Timestamp when event was created
    time_stamp: f64,
}

impl Event {
    /// Create a new Event
    pub fn new(event_type: &str) -> Self {
        Self::new_with_options(event_type, EventInit::default())
    }

    /// Create a new Event with options
    pub fn new_with_options(event_type: &str, init: EventInit) -> Self {
        Event {
            event_type: event_type.to_string(),
            target: RefCell::new(None),
            current_target: RefCell::new(None),
            related_target: RefCell::new(None),
            event_phase: RefCell::new(EventPhase::None),
            bubbles: init.bubbles,
            cancelable: init.cancelable,
            composed: init.composed,
            default_prevented: RefCell::new(false),
            stop_propagation_flag: RefCell::new(false),
            stop_immediate_propagation_flag: RefCell::new(false),
            dispatched: RefCell::new(false),
            _initialized: true,
            is_trusted: false,
            time_stamp: js_sys_now(),
        }
    }

    // === Getters ===

    /// Get event type
    pub fn event_type(&self) -> &str {
        &self.event_type
    }

    /// Alias for event_type (DOM spec uses "type")
    pub fn type_(&self) -> &str {
        &self.event_type
    }

    /// Get target
    pub fn target(&self) -> Option<JsObject> {
        self.target.borrow().clone()
    }

    /// Get current target
    pub fn current_target(&self) -> Option<JsObject> {
        self.current_target.borrow().clone()
    }

    /// Get related target
    pub fn related_target(&self) -> Option<JsObject> {
        self.related_target.borrow().clone()
    }

    /// Get event phase
    pub fn event_phase(&self) -> EventPhase {
        *self.event_phase.borrow()
    }

    /// Get bubbles
    pub fn bubbles(&self) -> bool {
        self.bubbles
    }

    /// Get cancelable
    pub fn cancelable(&self) -> bool {
        self.cancelable
    }

    /// Get composed
    pub fn composed(&self) -> bool {
        self.composed
    }

    /// Get defaultPrevented
    pub fn default_prevented(&self) -> bool {
        *self.default_prevented.borrow()
    }

    /// Get isTrusted
    pub fn is_trusted(&self) -> bool {
        self.is_trusted
    }

    /// Get timeStamp
    pub fn time_stamp(&self) -> f64 {
        self.time_stamp
    }

    // === Setters (for dispatch algorithm) ===

    /// Set target
    pub fn set_target(&self, target: Option<JsObject>) {
        *self.target.borrow_mut() = target;
    }

    /// Set current target
    pub fn set_current_target(&self, target: Option<JsObject>) {
        *self.current_target.borrow_mut() = target;
    }

    /// Set related target
    pub fn set_related_target(&self, target: Option<JsObject>) {
        *self.related_target.borrow_mut() = target;
    }

    /// Set event phase
    pub fn set_event_phase(&self, phase: EventPhase) {
        *self.event_phase.borrow_mut() = phase;
    }

    /// Mark as dispatched
    pub fn set_dispatched(&self, dispatched: bool) {
        *self.dispatched.borrow_mut() = dispatched;
    }

    /// Check if dispatched
    pub fn is_dispatched(&self) -> bool {
        *self.dispatched.borrow()
    }

    // === Methods ===

    /// Prevent default action
    pub fn prevent_default(&self) {
        if self.cancelable {
            *self.default_prevented.borrow_mut() = true;
        }
    }

    /// Stop propagation
    pub fn stop_propagation(&self) {
        *self.stop_propagation_flag.borrow_mut() = true;
    }

    /// Stop immediate propagation
    pub fn stop_immediate_propagation(&self) {
        *self.stop_propagation_flag.borrow_mut() = true;
        *self.stop_immediate_propagation_flag.borrow_mut() = true;
    }

    /// Check if propagation was stopped
    pub fn propagation_stopped(&self) -> bool {
        *self.stop_propagation_flag.borrow()
    }

    /// Check if immediate propagation was stopped
    pub fn immediate_propagation_stopped(&self) -> bool {
        *self.stop_immediate_propagation_flag.borrow()
    }

    /// Get composedPath (returns array of targets)
    pub fn composed_path(&self) -> Vec<JsObject> {
        // Simplified - would need full shadow DOM support
        if let Some(target) = self.target() {
            vec![target]
        } else {
            vec![]
        }
    }

    /// Initialize event (legacy method)
    pub fn init_event(&mut self, type_: &str, bubbles: bool, cancelable: bool) {
        if !self.is_dispatched() {
            *self.stop_propagation_flag.borrow_mut() = false;
            *self.stop_immediate_propagation_flag.borrow_mut() = false;
            *self.default_prevented.borrow_mut() = false;
            self.event_type = type_.to_string();
            // Note: bubbles and cancelable are immutable after construction in modern spec
        }
        let _ = bubbles;
        let _ = cancelable;
    }

    /// Create a trusted event (for user agent use)
    pub fn new_trusted(event_type: &str, init: EventInit) -> Self {
        let mut event = Self::new_with_options(event_type, init);
        event.is_trusted = true;
        event
    }
}

impl Default for Event {
    fn default() -> Self {
        Event::new("")
    }
}

impl ToJsValueBoa for Event {
    fn to_js_value(&self, ctx: &mut Context) -> JsResult<JsValue> {
        let obj = JsObject::with_null_proto();
        
        obj.set(js_string!("type"), JsValue::from(js_string!(self.event_type.as_str())), false, ctx)?;
        obj.set(js_string!("bubbles"), JsValue::from(self.bubbles), false, ctx)?;
        obj.set(js_string!("cancelable"), JsValue::from(self.cancelable), false, ctx)?;
        obj.set(js_string!("composed"), JsValue::from(self.composed), false, ctx)?;
        obj.set(js_string!("defaultPrevented"), JsValue::from(self.default_prevented()), false, ctx)?;
        obj.set(js_string!("isTrusted"), JsValue::from(self.is_trusted), false, ctx)?;
        obj.set(js_string!("timeStamp"), JsValue::from(self.time_stamp), false, ctx)?;
        obj.set(js_string!("eventPhase"), JsValue::from(self.event_phase() as i32), false, ctx)?;
        
        // target and currentTarget
        if let Some(target) = self.target() {
            obj.set(js_string!("target"), JsValue::from(target), false, ctx)?;
        } else {
            obj.set(js_string!("target"), JsValue::null(), false, ctx)?;
        }
        
        if let Some(current_target) = self.current_target() {
            obj.set(js_string!("currentTarget"), JsValue::from(current_target), false, ctx)?;
        } else {
            obj.set(js_string!("currentTarget"), JsValue::null(), false, ctx)?;
        }

        // Event phase constants
        obj.set(js_string!("NONE"), JsValue::from(0), false, ctx)?;
        obj.set(js_string!("CAPTURING_PHASE"), JsValue::from(1), false, ctx)?;
        obj.set(js_string!("AT_TARGET"), JsValue::from(2), false, ctx)?;
        obj.set(js_string!("BUBBLING_PHASE"), JsValue::from(3), false, ctx)?;

        Ok(JsValue::from(obj))
    }
}

