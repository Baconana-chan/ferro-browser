/// Initialize Event prototype
pub fn init_event_prototype(context: &mut Context) -> JsResult<JsObject> {
    let prototype = JsObject::with_null_proto();

    // Properties
    prototype.set(js_string!("type"), JsValue::from(js_string!("")), false, context)?;
    prototype.set(js_string!("target"), JsValue::null(), false, context)?;
    prototype.set(js_string!("currentTarget"), JsValue::null(), false, context)?;
    prototype.set(js_string!("eventPhase"), JsValue::from(0), false, context)?;
    prototype.set(js_string!("bubbles"), JsValue::from(false), false, context)?;
    prototype.set(js_string!("cancelable"), JsValue::from(false), false, context)?;
    prototype.set(js_string!("defaultPrevented"), JsValue::from(false), false, context)?;
    prototype.set(js_string!("composed"), JsValue::from(false), false, context)?;
    prototype.set(js_string!("isTrusted"), JsValue::from(false), false, context)?;
    prototype.set(js_string!("timeStamp"), JsValue::from(0.0), false, context)?;

    // Phase constants
    prototype.set(js_string!("NONE"), JsValue::from(0), false, context)?;
    prototype.set(js_string!("CAPTURING_PHASE"), JsValue::from(1), false, context)?;
    prototype.set(js_string!("AT_TARGET"), JsValue::from(2), false, context)?;
    prototype.set(js_string!("BUBBLING_PHASE"), JsValue::from(3), false, context)?;

    // Methods (stubs)
    let empty_func = JsObject::with_null_proto();
    prototype.set(js_string!("preventDefault"), JsValue::from(empty_func.clone()), false, context)?;
    prototype.set(js_string!("stopPropagation"), JsValue::from(empty_func.clone()), false, context)?;
    prototype.set(js_string!("stopImmediatePropagation"), JsValue::from(empty_func.clone()), false, context)?;
    prototype.set(js_string!("composedPath"), JsValue::from(empty_func), false, context)?;

    Ok(prototype)
}

/// Initialize CustomEvent prototype
pub fn init_custom_event_prototype(context: &mut Context) -> JsResult<JsObject> {
    let prototype = init_event_prototype(context)?;
    
    // Add detail property
    prototype.set(js_string!("detail"), JsValue::null(), false, context)?;
    
    Ok(prototype)
}

